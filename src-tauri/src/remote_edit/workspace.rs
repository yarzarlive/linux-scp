//! Managed on-disk workspace for remote editing working copies.
//!
//! Layout (all directories `0700`, files `0600`):
//!
//! ```text
//! <root>/                          $XDG_STATE_HOME/linuxscp/remote-edits (fallback: ~/.local/share/...)
//!   <session-uuid>/
//!     session.json                 manifest (no secrets; remote identity, baseline fingerprint + hash)
//!     work/<remote file name>      the working copy handed to the desktop application
//!     scratch/                     transient download/upload snapshots, removed after use
//! ```

use super::types::RemoteEditSession;
use crate::errors::AppError;
use sha2::{Digest, Sha256};
use std::fs;
use std::io::{Read, Write};
use std::os::unix::fs::{DirBuilderExt, MetadataExt, OpenOptionsExt, PermissionsExt};
use std::path::{Path, PathBuf};
use uuid::Uuid;

pub const MANIFEST_FILE: &str = "session.json";
pub const WORK_DIR: &str = "work";
pub const SCRATCH_DIR: &str = "scratch";

/// Resolves the default root for working copies.
///
/// `$XDG_STATE_HOME` is used instead of `$XDG_RUNTIME_DIR` deliberately: the runtime
/// directory is a tmpfs wiped at logout, which would silently destroy edits that have not
/// been uploaded yet (for example after a failed upload or a conflict).
pub fn default_workspace_root() -> Result<PathBuf, AppError> {
    let base = dirs::state_dir()
        .or_else(dirs::data_local_dir)
        .ok_or_else(|| {
            AppError::Filesystem(
                "Cannot determine a private state directory ($XDG_STATE_HOME or ~/.local/share) for remote editing working copies.".to_string(),
            )
        })?;
    Ok(base.join("linuxscp").join("remote-edits"))
}

/// Creates (if needed) a private directory owned by the current user with mode `0700`.
/// Refuses symlinks and directories owned by other users.
pub fn ensure_private_dir(path: &Path) -> Result<(), AppError> {
    if !path.exists() {
        fs::DirBuilder::new()
            .recursive(true)
            .mode(0o700)
            .create(path)
            .map_err(|e| {
                AppError::Filesystem(format!(
                    "Failed to create private directory '{}': {}",
                    path.display(),
                    e
                ))
            })?;
    }
    let meta = fs::symlink_metadata(path)
        .map_err(|e| AppError::Filesystem(format!("Cannot inspect '{}': {}", path.display(), e)))?;
    if meta.file_type().is_symlink() || !meta.is_dir() {
        return Err(AppError::Security(format!(
            "Refusing to use '{}' for remote editing: it is not a regular directory.",
            path.display()
        )));
    }
    // SAFETY: geteuid has no preconditions and cannot fail.
    let euid = unsafe { libc::geteuid() };
    if meta.uid() != euid {
        return Err(AppError::Security(format!(
            "Refusing to use '{}' for remote editing: it is owned by another user.",
            path.display()
        )));
    }
    if meta.permissions().mode() & 0o777 != 0o700 {
        fs::set_permissions(path, fs::Permissions::from_mode(0o700)).map_err(|e| {
            AppError::Filesystem(format!(
                "Failed to restrict permissions on '{}': {}",
                path.display(),
                e
            ))
        })?;
    }
    Ok(())
}

/// Validates a remote base name before using it as a local file name.
pub fn validate_local_file_name(name: &str) -> Result<String, AppError> {
    let trimmed = name.trim_end_matches('/');
    let base = trimmed.rsplit('/').next().unwrap_or(trimmed);
    if base.is_empty() || base == "." || base == ".." || base.contains('\0') {
        return Err(AppError::Validation(format!(
            "Remote path '{}' does not name a file that can be opened.",
            name
        )));
    }
    Ok(base.to_string())
}

/// Paths of one session directory.
#[derive(Debug, Clone)]
pub struct SessionPaths {
    pub dir: PathBuf,
    pub work_dir: PathBuf,
    pub scratch_dir: PathBuf,
    pub manifest: PathBuf,
}

impl SessionPaths {
    pub fn new(root: &Path, session_id: &str) -> Self {
        let dir = root.join(session_id);
        Self {
            work_dir: dir.join(WORK_DIR),
            scratch_dir: dir.join(SCRATCH_DIR),
            manifest: dir.join(MANIFEST_FILE),
            dir,
        }
    }

    pub fn create(&self) -> Result<(), AppError> {
        ensure_private_dir(&self.dir)?;
        ensure_private_dir(&self.work_dir)?;
        ensure_private_dir(&self.scratch_dir)?;
        Ok(())
    }

    pub fn scratch_file(&self, prefix: &str) -> PathBuf {
        self.scratch_dir
            .join(format!("{}-{}.part", prefix, Uuid::new_v4()))
    }
}

/// Session ids are UUIDs generated by LinuxSCP; reject anything else before touching disk.
pub fn validate_session_id(id: &str) -> Result<(), AppError> {
    Uuid::parse_str(id)
        .map(|_| ())
        .map_err(|_| AppError::Validation(format!("Invalid remote edit session id '{}'.", id)))
}

/// Removes a session directory after verifying it lies directly under `root`.
pub fn remove_session_dir(root: &Path, session_id: &str) -> Result<(), AppError> {
    validate_session_id(session_id)?;
    let dir = root.join(session_id);
    if dir.parent() != Some(root) {
        return Err(AppError::Security(
            "Refusing to remove a directory outside the remote edit workspace.".to_string(),
        ));
    }
    match fs::symlink_metadata(&dir) {
        Ok(meta) if meta.file_type().is_symlink() => Err(AppError::Security(format!(
            "Refusing to remove symlinked session directory '{}'.",
            dir.display()
        ))),
        Ok(_) => fs::remove_dir_all(&dir).map_err(|e| {
            AppError::Filesystem(format!(
                "Failed to remove working copy directory '{}': {}",
                dir.display(),
                e
            ))
        }),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(AppError::Filesystem(format!(
            "Cannot inspect '{}': {}",
            dir.display(),
            e
        ))),
    }
}

/// Writes the manifest atomically (temp file + rename) with mode `0600`.
pub fn write_manifest(paths: &SessionPaths, session: &RemoteEditSession) -> Result<(), AppError> {
    let json = serde_json::to_vec_pretty(session)
        .map_err(|e| AppError::Internal(format!("Failed to serialize edit manifest: {}", e)))?;
    let tmp = paths.dir.join(format!(".{}.tmp", MANIFEST_FILE));
    {
        let mut f = fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(0o600)
            .open(&tmp)
            .map_err(|e| AppError::Filesystem(format!("Failed to write edit manifest: {}", e)))?;
        f.write_all(&json)
            .and_then(|_| f.sync_all())
            .map_err(|e| AppError::Filesystem(format!("Failed to write edit manifest: {}", e)))?;
    }
    fs::rename(&tmp, &paths.manifest)
        .map_err(|e| AppError::Filesystem(format!("Failed to finalize edit manifest: {}", e)))
}

pub fn read_manifest(path: &Path) -> Result<RemoteEditSession, AppError> {
    let bytes = fs::read(path)
        .map_err(|e| AppError::Filesystem(format!("Cannot read '{}': {}", path.display(), e)))?;
    serde_json::from_slice(&bytes).map_err(|e| {
        AppError::Filesystem(format!("Corrupt edit manifest '{}': {}", path.display(), e))
    })
}

/// Streaming SHA-256 of a local file, returned as lowercase hex.
pub fn sha256_file(path: &Path) -> std::io::Result<String> {
    let mut file = fs::File::open(path)?;
    let mut hasher = Sha256::new();
    let mut buf = vec![0u8; 64 * 1024];
    loop {
        let n = file.read(&mut buf)?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
    }
    Ok(hasher
        .finalize()
        .iter()
        .map(|b| format!("{:02x}", b))
        .collect())
}

/// Cheap local change indicator used by the poller before hashing.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct LocalStat {
    pub len: u64,
    pub mtime_ns: i128,
    pub ctime_ns: i128,
    pub ino: u64,
}

pub fn local_stat(path: &Path) -> Option<LocalStat> {
    let meta = fs::metadata(path).ok()?;
    if !meta.is_file() {
        return None;
    }
    Some(LocalStat {
        len: meta.len(),
        mtime_ns: i128::from(meta.mtime()) * 1_000_000_000 + i128::from(meta.mtime_nsec()),
        ctime_ns: i128::from(meta.ctime()) * 1_000_000_000 + i128::from(meta.ctime_nsec()),
        ino: meta.ino(),
    })
}

/// Copies a file into a new `0600` file (used for upload snapshots and user copies).
pub fn copy_private(src: &Path, dest: &Path) -> std::io::Result<u64> {
    let mut input = fs::File::open(src)?;
    let mut output = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(dest)?;
    let n = std::io::copy(&mut input, &mut output)?;
    output.sync_all()?;
    Ok(n)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_root() -> PathBuf {
        std::env::temp_dir().join(format!("linuxscp-ws-test-{}", Uuid::new_v4()))
    }

    #[test]
    fn private_dirs_are_0700_and_symlinks_rejected() {
        let root = temp_root();
        ensure_private_dir(&root).unwrap();
        let mode = fs::metadata(&root).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode, 0o700);

        let link = root.with_extension("link");
        std::os::unix::fs::symlink(&root, &link).unwrap();
        assert!(matches!(
            ensure_private_dir(&link),
            Err(AppError::Security(_))
        ));
        fs::remove_file(&link).unwrap();
        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn file_name_validation() {
        assert_eq!(
            validate_local_file_name("/etc/nginx/nginx.conf").unwrap(),
            "nginx.conf"
        );
        assert_eq!(validate_local_file_name("notes.txt").unwrap(), "notes.txt");
        assert!(validate_local_file_name("/").is_err());
        assert!(validate_local_file_name("/srv/..").is_err());
    }

    #[test]
    fn remove_session_dir_rejects_non_uuid_ids() {
        let root = temp_root();
        ensure_private_dir(&root).unwrap();
        assert!(remove_session_dir(&root, "../etc").is_err());
        assert!(remove_session_dir(&root, "abc").is_err());
        let id = Uuid::new_v4().to_string();
        fs::create_dir_all(root.join(&id).join("work")).unwrap();
        remove_session_dir(&root, &id).unwrap();
        assert!(!root.join(&id).exists());
        fs::remove_dir_all(&root).unwrap();
    }

    #[test]
    fn sha256_matches_known_vector() {
        let root = temp_root();
        ensure_private_dir(&root).unwrap();
        let f = root.join("abc.txt");
        fs::write(&f, b"abc").unwrap();
        assert_eq!(
            sha256_file(&f).unwrap(),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        fs::remove_dir_all(&root).unwrap();
    }
}
